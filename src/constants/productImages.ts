const LOREM_FLICKR_DYNAMIC_URL = /^https?:\/\/(?:www\.)?loremflickr\.com\/640\/480\//i;

/**
 * Replaces the redirecting seed URL with its fixed image URL. Real URLs saved
 * from the admin panel pass through unchanged.
 */
export function getProductImage(productId: string, currentImage: string): string {
  if (!LOREM_FLICKR_DYNAMIC_URL.test(currentImage)) return currentImage;
  return STABLE_PRODUCT_IMAGES[productId] ?? '';
}
